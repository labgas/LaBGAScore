        model_parameters = '-s 0 -t 0 -c 1 -b 0 -q';   % C-SVC, linear kernel
        scale_method     = 'z';
        scale_estimation = 'across';
    otherwise
        error('scaling_regime must be ''kernel'' or ''strict''');
end

