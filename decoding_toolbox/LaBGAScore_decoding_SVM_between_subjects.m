%% LaBGAScore_decoding_SVM_between_subjects.m
%
%
% *USAGE*
%
% BETWEEN-SUBJECT SVM DECODING WITH PERMUTATION-BASED TFCE INFERENCE
%
% This script implements a complete second-level between-subject MVPA
% decoding pipeline using The Decoding Toolbox (TDT). It performs group-level
% SVM classification (patients vs controls), permutation-based statistical
% inference, and Threshold-Free Cluster Enhancement (TFCE) for spatially
% informed whole-brain, ROI, or searchlight decoding analyses.
%
% Statistical inference is non-parametric throughout and based on empirical
% permutation null distributions. TFCE constitutes the primary inferential
% framework, supplemented by voxel-wise permutation p-values and FDR
% correction for interpretability.
%
% The pipeline is designed for reproducibility, scalability, and integration
% with the Canlab neuroimaging framework.
%
% The script executes the following steps:
%
% 1. Data Preparation
%    - Loads phenotype information (participant IDs, group labels).
%    - Constructs balanced K-fold cross-validation (CV) partitions
%      separately for patients and controls.
%    - Assigns chunk labels and class labels to each subject.
%    - Loads first-level contrast images for all subjects.
%
% 2. Decoding Configuration (TDT)
%    Between-subject linear SVM decoding using The Decoding Toolbox,
%    supporting three analysis modes:
%
%      * 'searchlight' : spherical multivoxel decoding maps
%      * 'roi'         : decoding within multiple predefined ROIs
%      * 'wholebrain'  : decoding using a full-brain mask
%
%    Key configuration choices include:
%      - Linear C-SVC, identical for real and permutation runs. Two regimes,
%        selected by scaling_regime: 'kernel' (classification_kernel, scaling
%        estimated on all data - TDT's own recommendation, and much faster) or
%        'strict' (classification, train-only 'across' scaling, no kernel)
%      - Cross-validation folds balanced across groups, and across any
%        variable named in cv_strata_vars within group
%      - Scaling per scaling_regime, applied identically to real and null
%      - Explicit handling of unbalanced group sizes
%      - Performance metric: AUC minus chance
%
% 3. Real (Unpermuted) Decoding
%    - Runs decoding once using the true group labels.
%    - Extracts the voxel-wise decoding statistic vector (real_vec),
%      consistent across analysis modes.
%
% 4. Permutation Design Generation
%    - Generates N permutation designs using TDT's permutation framework.
%    - Permutations preserve the cross-validation structure while
%      destroying the label–group relationship.
%
% 5. Fast Permutation Decoding (In-Memory)
%    - Executes permutation decodings using parfor for efficiency.
%    - Uses THE SAME classifier and scaling as the real run. This is not a
%      detail: a null generated by a different procedure is not the null
%      distribution of the real statistic. See the note at the cfg block.
%    - Reuses passed_data and misc from the real run, so the images are read
%      and the searchlight neighbourhoods computed ONCE rather than once per
%      permutation.
%    - Avoids writing intermediate output folders or NIfTI files.
%    - Collects the empirical null distribution in memory as:
%
%          all_perm_results [nVoxels × nPermutations]
%
%    - Live progress and ETA reporting are provided during permutation runs.
%
% 6. Voxel-wise Permutation Statistics
%    - Computes empirical voxel-wise p-values from the permutation null:
%
%          p_unc(v) = ( #{perm >= real} + 1 ) / (nPerm + 1)
%
%    - Generates uncorrected and FDR-corrected voxel-wise p-maps for
%      complementary assessment of decoding effects.
%
% 7. TFCE-Based Inference (Primary)
%    - Converts decoding statistics to voxel-wise t-maps using the
%      permutation-derived mean and standard deviation.
%    - Applies Threshold-Free Cluster Enhancement (TFCE, Smith & Nichols
%      2009) via tfce_volume, shared with the secondlevel TFCE stack.
%    - Computes a permutation-based TFCE null distribution (in parallel).
%
%    TFCE inference includes:
%      - Global FWE-corrected TFCE p-value (max-statistic)
%      - Voxel-wise TFCE p-values (uncorrected)
%      - Voxel-wise FDR-corrected TFCE p-values
%      - Voxel-wise FWE-corrected TFCE p-values (using the TFCE max-statistic)
%
%    TFCE results constitute the primary inferential outcome of this
%    pipeline, providing spatially informed, permutation-based control
%    of family-wise error.
%
% 8. Canlab Output Generation
%    - Converts decoding statistics and p-maps into Canlab-compatible
%      representations:
%        * fmri_data_st objects
%        * region objects with atlas-based labels
%        * summary tables for reporting and visualization
%
%
% *OPTIONS*
%
% Set in the "0. USER SETTINGS" section below:
%
% * pheno_id_var            phenotype column holding sub-* identifiers, used to build image paths
% * pheno_group_var         phenotype column holding the group variable
% * group_pos_code / group_neg_code    values of that column for class +1 / -1
% * group_pos_name / group_neg_name    labels used in printouts
%
%       CHECK THE GROUP CODING. Getting it backwards silently swaps the two
%       classes: nothing errors, and every reported direction is reversed.
%
% * K                       number of cross-validation folds, balanced between patients and controls, default 5
% * cv_strata_vars          cell array of phenotype columns to balance across folds IN ADDITION to
%                           group, e.g. {'PET_MR'} for scanner. Stratification is not the same as
%                           regressing the variable out - TDT has no covariate hook - but it removes
%                           the failure mode that matters with a small nuisance stratum, namely a
%                           fold holding all or none of it
% * cv_seed                 seed for fold assignment; previously unset, so folds differed every run
% * con2use                 contrast image filename (con_XXXX.nii) to decode on
% * performance_metric      TDT performance metric, script only tested with {'AUC_minus_chance'}
% * unbalanced               true/false, whether to allow unbalanced group sizes in cfg.design
% * analysis_mode           'searchlight' | 'roi' | 'wholebrain'
%                               if 'searchlight': searchlight_radius (mm), mask_file (whole-brain mask for the searchlight)
%                                                 searchlight_subset - TIMING BENCHMARK ONLY, leave empty ([])
%                                                 for any real analysis. An Nx1 LIST OF SEARCHLIGHT
%                                                 INDICES (or Nx3 XYZ coords) - NOT a decimation
%                                                 factor: the scalar 20 runs ONE centre, not every
%                                                 20th, and TDT accepts it silently. TDT returns 0, not NaN, for centres it did
%                                                 not run, and 0 is a legitimate AUC_minus_chance
%                                                 (exactly chance), so skipped centres CANNOT be told
%                                                 apart from real ones downstream: they would enter the
%                                                 FDR correction and the TFCE null as genuine
%                                                 chance-level data. The script therefore refuses to run
%                                                 inference when it is set, and stops after the timings.
%                               if 'roi': roi_list (cell array of ROI mask paths)
%                               if 'wholebrain': mask_file
% * n_perms                 number of permutations for the null distribution, default 1000
% * atlas                   CANlab atlas used for region labeling, default 'canlab2024'
% * unc_p / unc_k            uncorrected p-value / extent threshold for output fmri_data objects
% * fdr_p / fdr_k            FDR-corrected p-value / extent threshold for output fmri_data objects
% * fwe_p / fwe_k            TFCE FWE-corrected p-value / extent threshold for output fmri_data objects
% * combat_batch_var        phenotype column holding site/batch labels, e.g. 'center'; empty disables
%                           ComBat. Harmonisation here is LABEL-BLIND (mod = []) by design: telling
%                           ComBat to preserve the variable being decoded would leak labels into the
%                           features. Features that are constant across all samples, or constant
%                           within any one site, are excluded from harmonisation and passed through
%                           untouched - combat.m errors on the first and returns NaN on the second.
% * combat_ref              site label to harmonise towards; empty harmonises to the grand mean
% * export_conidx           contrast index to export when scaled_contrast_dir is empty;
%                           defaults to con2use when that is a scalar index
% * export_object           contrast object to export: 'DATA_OBJ_CON' (raw),
%                           'DATA_OBJ_CONsc' (z-scored conditions) or 'DATA_OBJ_CONscc'.
%                           Defaults from myscaling_glm, so it matches the GLM by default
% * scaled_contrast_dir     directory of per-subject contrast NIfTIs written by
%                           LaBGAScore_export_scaled_contrasts. Set this to decode the SAME images the
%                           second-level GLM used; leave empty to read raw first-level
%                           contrasts. If the directory is empty or absent it is POPULATED
%                           automatically by LaBGAScore_export_scaled_contrasts
% * contrast_objects_tag    default ''; suffix identifying WHICH set of contrast objects to
%                           export features from, for a model that harmonises more than one way.
%                           A GLM path harmonised with combat_mod = {'group'} is not a valid
%                           feature source for a classifier: ComBat adds the fitted group effect
%                           back into its own output, so every image carries a term proportional
%                           to its own subject's label. Point this at the label-blind path.
% * scaling_regime          'kernel' (TDT's recommended estimation = 'all', precomputed kernel reused
%                           across permutations) or 'strict' ('across', train-fold-only scaling;
%                           measured 12-25x slower because the kernel cannot be reused)
%
%
% *DEPENDENCIES*
%
% - MATLAB R2018a or newer
% - The Decoding Toolbox (TDT)
% - LaBGAScore secondlevel/functions on the MATLAB path (tfce_volume,
%   tfce_transform_3d) and the Image Processing Toolbox for bwconncomp
% - SPM12 (recommended for NIfTI I/O)
% - NIfTI utilities (load_nii / save_nii)
% - Canlab toolbox (fmri_data_st, region, atlas utilities)
% - This repo's ProgressTracker class (secondlevel/classes/),
%   LaBGAScore_smart_parallel_pool_setup.m (clean/), and
%   secondlevel/functions/thresholded_fmri_data_from_pval_nii.m
%
% - phenotype.csv in BIDSdir containing:
%      * participant identifiers
%      * group labels (patient / control)
%
% - First-level contrast images (con_XXXX.nii) for all subjects
% - Valid brain mask (whole-brain / searchlight) or ROI masks
%
%
% *KNOWN-BAD PREDECESSORS*
%
% Results produced by earlier versions of this script, and by study copies of
% them, used a ONE-CLASS SVM ('-s 2') for the permutation null while the real
% statistic came from a C-SVC. The null therefore came from a model that never
% saw the training labels, and every permutation p-value built on it -
% uncorrected, FDR and TFCE - is invalid. proj_cfs model_8 is affected. Do not
% cite those p-values; re-run with this version instead.
%
%
% *NOTES*
%
% All outputs are written to tdt_resultsdir/, including:
%
% - NIfTI files:
%      * decoding statistic maps
%      * voxel-wise permutation p-maps
%      * TFCE-enhanced maps
%      * TFCE-based p-maps (voxel-wise, FDR, and FWE)
%
% - MATLAB files:
%      * combined_permutations.mat
%          - real_vec
%          - all_perm_results
%          - analysis metadata
%
% - Canlab objects:
%      * fmri_data_st objects (statistics and p-maps)
%      * region objects (TFCE- or voxel-wise thresholded clusters)
%      * summary tables with atlas-based annotations
%
% - All statistical inference is non-parametric and permutation-based.
% - TFCE is used as the primary method for spatial inference, with explicit
%   control of family-wise error via the permutation-derived max-statistic.
% - The script is fully non-interactive and suitable for HPC execution.
% - No temporary decoding folders or files are written during permutation
%   decoding.
