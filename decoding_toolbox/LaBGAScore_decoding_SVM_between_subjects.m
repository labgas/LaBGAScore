    chunk_list = chunk_list(~cellfun(@isempty, chunk_list));
    n_chunks_eff = numel(chunk_list);

    fprintf('  combined designs: %d chunk(s), ~%d permutation(s) each\n', ...
        n_chunks_eff, round(n_perms/n_chunks_eff));

